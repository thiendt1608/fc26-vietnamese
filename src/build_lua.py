"""Generate Live Editor autorun files.
  python src/build_lua.py --english   # full-scale load test: every unit with its English source
  python src/build_lua.py             # real: data/translations.jsonl (status ok|flagged|manual, vi != source)
  python src/build_lua.py --file data/pilot_X.jsonl --prefix pilot_x   # pilot set -> lua/pilot_x_01.lua
Output: lua/<prefix>_NN.lua (default prefix viet_hoa_auto), then verified offline with lupa (Lua 5.4)."""
import json, sys, glob, os
from common import *

PER_FILE = 10000
HEAD = "-- generated by build_lua.py; edit translations.jsonl, not this file\nlocal T = {\n"
TAIL = '''}
local ok, bad = 0, 0
for i = 1, #T, 2 do
  if pcall(SetGameLocString, T[i], T[i + 1]) then ok = ok + 1 else bad = bad + 1 end
end
print(("%s: %d ok, %d failed"):format("NAME", ok, bad))
pcall(function()
  local f = io.open("C:/FC 26 Live Editor/viet_hoa_log.txt", "a")
  f:write(("%s: %d ok, %d failed\\n"):format("NAME", ok, bad))
  f:close()
end)
'''

def arg(name, default):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default

def load_pairs(english):
    pairs = {}
    if english:
        for ln in open(ROOT / "data" / "units.jsonl", encoding="utf-8"):
            u = json.loads(ln)
            for i in u["ids"]:
                pairs[i] = u["source"]
    else:
        for ln in open(ROOT / arg("--file", "data/translations.jsonl"), encoding="utf-8"):
            u = json.loads(ln)
            if u["status"] in ("ok", "flagged", "manual") and u["vi"] != u["source"]:
                for i in u["ids"]:
                    pairs[i] = u["vi"]
    return sorted(pairs.items())

def expected_text(s):
    """What the game should receive (after escape decoding)."""
    return (s.replace("\\r\\n", "\r\n").replace("\\n", "\n").replace("\\r", "\r").replace("\\t", "\t"))

def main():
    pairs = load_pairs("--english" in sys.argv)
    out = ROOT / "lua"
    prefix = arg("--prefix", "viet_hoa_auto")
    for f in glob.glob(str(out / f"{prefix}_*.lua")):
        os.remove(f)
    names = []
    for n, i in enumerate(range(0, len(pairs), PER_FILE), 1):
        name = f"{prefix}_{n:02d}"
        body = "".join(f"{lua_str(k)}, {lua_str(v)},\n" for k, v in pairs[i:i + PER_FILE])
        (out / f"{name}.lua").write_bytes((HEAD + body + TAIL.replace("NAME", name)).encode("utf-8"))
        names.append(name)
    print(f"{len(pairs)} pairs -> {len(names)} files, "
          f"{sum(os.path.getsize(out / (n + '.lua')) for n in names) / 1e6:.1f} MB")

    # offline self-check
    from lupa import lua54
    got, dup = {}, 0
    L = lua54.LuaRuntime(encoding=None)
    def setter(k, v):
        nonlocal dup
        k = k.decode()
        dup += k in got
        got[k] = v.decode()
    L.globals().SetGameLocString = setter
    L.globals().print = lambda *a: None
    L.execute("io = nil")
    for n in names:
        L.execute((out / f"{n}.lua").read_bytes())
    bad = [k for k, v in pairs if got.get(k) != expected_text(v)]
    assert len(got) == len(pairs) and not dup and not bad, (len(got), dup, bad[:5])
    print("lupa self-check: all pairs match, no duplicate ids")

main()
